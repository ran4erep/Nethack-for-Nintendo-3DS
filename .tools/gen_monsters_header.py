def generate_header(out_path="sys/3ds/3dsmonsters.h"):
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("/* sys/3ds/3dsmonsters.h - Russian monster dictionary for NetHack 3DS */\n")
        f.write("#ifndef _3DSMONSTERS_H\n")
        f.write("#define _3DSMONSTERS_H\n\n")
        f.write("struct mon_tr {\n")
        f.write("    const char *en;\n")
        f.write("    const char *ru_utf8;\n")
        f.write("    char ru_cp1251[128];\n")
        f.write("};\n\n")
        f.write("static struct mon_tr monster_dictionary[] = {\n")
        for en, ru in sorted(MONSTER_TRANSLATIONS.items()):
            # Escape quotes if any
            en_esc = en.replace('"', '\\"')
            ru_esc = ru.replace('"', '\\"')
            f.write(f'    {{ "{en_esc}", "{ru_esc}", "" }},\n')
        f.write("};\n\n")
        f.write("#endif /* _3DSMONSTERS_H */\n")
    print(f"Generated {len(MONSTER_TRANSLATIONS)} monsters in {out_path}")

if __name__ == "__main__":
    generate_header()
