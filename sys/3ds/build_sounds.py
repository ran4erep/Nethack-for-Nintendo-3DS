#!/usr/bin/env python3
"""Turn a 3DS sound pack into the romfs tree and the generated key table.

Effects are read from a plain numbered tree when it exists:

    soundpack/new/<key>/0.mp3            base sound
    soundpack/new/<key>/1.mp3            variation 1, 2, ...

Otherwise the script falls back to the manifest-based pack:

    soundpack/manifest.json
    soundpack/sounds/<key>/base/<file>.mp3
    soundpack/sounds/<key>/<variation-id>/<file>.mp3

Every effect is decoded to 16-bit mono 22050 Hz PCM and normalized: the
loudest 50 ms of each clip is brought to SFX_TARGET_DB and a limiter keeps
the peaks below about -1 dBFS.  This makes files recorded at very different
levels play at a consistent volume.

Output is four things:

    <romfs>/sounds/<key>/<n>.wav         16-bit mono PCM, n = 0 for the base
                                          sound and 1.. for its variations
    <romfs>/music/menu.wav               looping menu music (if
                                          soundpack/menu.mp3 exists)
    <romfs>/music/game.wav               looping gameplay music (if
                                          soundpack/loop.mp3 exists)
    <out>                                C header with the key table
                                          (build3ds/sndpack.h)

All are consumed by sys/3ds/3dssnd.c.  The conversion needs ffmpeg; if
ffmpeg or the pack is missing the script still writes a valid, empty header
so the build succeeds (the game then just plays nothing).

Run it directly after replacing the pack, or use the make target:

    make -f sys/3ds/Makefile.3ds sounds
"""

import argparse
import array
import json
import math
import os
import shutil
import subprocess
import sys
import wave

SAMPLE_RATE = 22050  # 16-bit mono; small and plenty for effects

# Effects are normalized to the same loudness: the loudest 50 ms of each
# clip is brought to SFX_TARGET_DB, then a limiter keeps the peaks around
# -1 dBFS.  The raw pack has a ~30 dB spread between the quietest and
# loudest files, so this is what makes footsteps, doors and hits sit at a
# similar level in the game.
SFX_TARGET_DB = -3.0
SFX_TOLERANCE_DB = 1.0
SFX_MAX_GAIN_DB = 50.0
SFX_LIMIT = 0.891  # linear, about -1 dBFS
SFX_ITERATIONS = 3
AUDIO_EXTS = (".mp3", ".ogg", ".wav", ".flac", ".m4a")

# Music.  The 3DS plays PCM, not MP3, so the source is decoded and cut
# to a loop that stays around 2 MB: 45 s * 22050 Hz * 2 bytes = 1.98 MB.
# The loop starts after the track's fade-in (MUSIC_START); the MUSIC_XFADE
# seconds just before that point are the "pre-roll".  The tail is
# crossfaded into the pre-roll, so wrapping from the end back to the start
# continues the waveform.  Starting at 0 instead would blend the tail into
# near-silence and put an audible dip in every loop.
# Both looping tracks are normalized to MUSIC_TARGET_DB; the menu track used
# to keep the source's own level but is now matched to the gameplay loop.
MUSIC_RATE = 22050
MUSIC_START = 4.0
MUSIC_SECONDS = 45.0
MUSIC_XFADE = 0.75
MUSIC_MAX_BYTES = 2 * 1024 * 1024
MUSIC_TARGET_DB = -5.0


def warn(msg):
    sys.stderr.write("build_sounds: %s\n" % msg)


def write_empty(out_path, reason):
    warn("%s -- building with no sound effects" % reason)
    _write_header(out_path, [], 1)


def _write_header(out_path, keys, maxvars):
    """keys is a list of (key, [vol...]) with one volume per wav file."""
    out_dir = os.path.dirname(out_path)
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)

    lines = []
    lines.append("/* Generated by sys/3ds/build_sounds.py -- do not edit.")
    lines.append(" *")
    lines.append(" * The sound pack and how to replace it are described in")
    lines.append(" * sys/3ds/README.md.  Each key maps to sounds/<key>/<n>.wav.")
    lines.append(" */")
    lines.append("#ifndef SNDPACK_H")
    lines.append("#define SNDPACK_H")
    lines.append("")
    lines.append("#define SNDPACK_MAXVARS %d" % maxvars)
    lines.append("")
    lines.append("struct sndpack_key {")
    lines.append("    const char *key;            /* lookup key used by the port */")
    lines.append("    unsigned char count;        /* variations after the base */")
    lines.append("    float vol[SNDPACK_MAXVARS]; /* [0]=base, [1..count]=variations */")
    lines.append("};")
    lines.append("")
    lines.append("#define sndpack_num_keys %d" % len(keys))
    if keys:
        lines.append("")
        lines.append("static const struct sndpack_key sndpack_keys[] = {")
        for key, vols in keys:
            vol_text = ", ".join("%.3ff" % v for v in vols)
            lines.append('    { "%s", %d, { %s } },'
                         % (key, len(vols) - 1, vol_text))
        lines.append("};")
    else:
        # zero-length arrays are not allowed in C; the count macro is 0 so
        # this slot is never dereferenced
        lines.append("")
        lines.append("static const struct sndpack_key sndpack_keys[1];")
    lines.append("")
    lines.append("#endif /* SNDPACK_H */")

    with open(out_path, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def decode_pcm(ffmpeg, src, rate=SAMPLE_RATE):
    """Decode the source to signed 16-bit mono PCM at `rate`."""
    cmd = [ffmpeg, "-v", "error", "-i", src, "-ac", "1", "-ar", str(rate),
           "-f", "s16le", "-acodec", "pcm_s16le", "pipe:1"]
    try:
        proc = subprocess.run(cmd, check=True, stdout=subprocess.PIPE,
                              stderr=subprocess.PIPE)
    except (OSError, subprocess.CalledProcessError) as e:
        warn("ffmpeg failed for %s (%s)" % (src, e))
        return None
    samples = array.array("h")
    samples.frombytes(proc.stdout[:len(proc.stdout) & ~1])
    if sys.byteorder != "little":
        samples.byteswap()
    return samples


def read_wav_pcm(path):
    """Read a 16-bit mono PCM WAV (the files convert() writes)."""
    w = wave.open(path, "rb")
    try:
        data = w.readframes(w.getnframes())
    finally:
        w.close()
    samples = array.array("h")
    samples.frombytes(data[:len(data) & ~1])
    if sys.byteorder != "little":
        samples.byteswap()
    return samples


def rms_db(samples):
    if not samples:
        return -999.0
    r = math.sqrt(sum(v * v for v in samples) / len(samples))
    return 20.0 * math.log10(max(r, 1e-9) / 32768.0)


def loudest_window_db(samples, ms=50.0, rate=SAMPLE_RATE):
    """RMS of the loudest `ms`-long window, in dBFS.

    Whole-clip RMS is misleading for sounds with a long quiet tail or a
    single transient; the loudest short window tracks perceived level much
    better for effects.
    """
    if not samples:
        return -999.0
    win = max(1, int(rate * ms / 1000.0))
    if len(samples) <= win:
        return rms_db(samples)
    step = max(1, win // 4)
    best = 0.0
    for i in range(0, len(samples) - win + 1, step):
        seg = samples[i:i + win]
        r = math.sqrt(sum(v * v for v in seg) / win)
        if r > best:
            best = r
    return 20.0 * math.log10(max(best, 1e-9) / 32768.0)


def convert(ffmpeg, src, dst):
    """Convert one effect to 22050 mono PCM and match its loudness."""
    os.makedirs(os.path.dirname(dst), exist_ok=True)

    samples = decode_pcm(ffmpeg, src)
    if not samples:
        return False

    level = loudest_window_db(samples)
    if level < -70.0:
        warn("%s is nearly silent; leaving its level alone" % src)
        gain_db = 0.0
    else:
        gain_db = SFX_TARGET_DB - level
    gain_db = max(-SFX_MAX_GAIN_DB, min(SFX_MAX_GAIN_DB, gain_db))

    # Re-measure after limiting: a very peaky clip can end up below the
    # target because the limiter pulled its loudest part down.
    for _ in range(SFX_ITERATIONS):
        cmd = [ffmpeg, "-y", "-loglevel", "error", "-i", src,
               "-af", ("volume=%.2fdB,alimiter=limit=%.3f"
                       ":attack=5:release=50:level=disabled"
                       % (gain_db, SFX_LIMIT)),
               "-ac", "1", "-ar", str(SAMPLE_RATE), "-c:a", "pcm_s16le",
               dst]
        try:
            subprocess.run(cmd, check=True)
        except (OSError, subprocess.CalledProcessError) as e:
            warn("ffmpeg failed for %s (%s)" % (src, e))
            return False

        out_level = loudest_window_db(read_wav_pcm(dst))
        if abs(out_level - SFX_TARGET_DB) <= SFX_TOLERANCE_DB:
            return True
        gain_db += SFX_TARGET_DB - out_level
        gain_db = max(-SFX_MAX_GAIN_DB, min(SFX_MAX_GAIN_DB, gain_db))
    return True


# Music tracks built from the source files below: soundpack/<stem>.mp3 (or
# soundpack/music/<stem>.*) becomes romfs/music/<name>.wav.  The menu track
# covers the main menu and character creation; the gameplay loop plays from
# the first turn on.  target_db optionally normalizes the loop's loudness.
MUSIC_TRACKS = (
    ("menu", "menu", MUSIC_TARGET_DB),
    ("loop", "game", MUSIC_TARGET_DB),
)


def find_music(soundpack, stem):
    """Locate a music track source, either at the pack root or under music/."""
    for sub in ("", "music"):
        for ext in (".mp3", ".ogg", ".wav", ".flac", ".m4a"):
            name = stem + ext
            path = os.path.join(soundpack, sub, name) if sub else \
                os.path.join(soundpack, name)
            if os.path.isfile(path):
                return path
    return None


def normalize_to_db(samples, target_db):
    """Scale a sample array so its loudest 50 ms window reaches target_db.

    Clips to the same limiter ceiling the effects use.  Returns a new
    array; nearly-silent input is returned unchanged.
    """
    level = loudest_window_db(samples)
    if level < -70.0:
        return samples
    gain_db = max(-SFX_MAX_GAIN_DB, min(SFX_MAX_GAIN_DB, target_db - level))
    scale = 10 ** (gain_db / 20.0)
    limit = SFX_LIMIT * 32768.0
    peak = max(abs(v) for v in samples) if samples else 0
    if peak * scale > limit:
        scale = limit / peak
    return array.array("h", (int(v * scale) for v in samples))


def convert_music(ffmpeg, src, dst, target_db=None):
    """Decode a track into a seamless, ~2 MB 16-bit mono loop.

    The output is MUSIC_SECONDS long.  It is taken from the source after
    MUSIC_START (so the track's fade-in is not looped as near-silence), and
    the MUSIC_XFADE seconds preceding that point are the pre-roll: the tail
    is crossfaded into that pre-roll, so wrapping from the end back to the
    start continues the waveform instead of clicking or going silent.  If
    target_db is not None, the finished loop is normalized to that loudness.
    Returns the number of PCM bytes written, or None on failure.
    """
    start = int(MUSIC_START * MUSIC_RATE)
    xfade = int(MUSIC_XFADE * MUSIC_RATE)
    loop = int(MUSIC_SECONDS * MUSIC_RATE)
    want = start + loop + xfade
    cmd = [
        ffmpeg, "-y", "-loglevel", "error", "-i", src,
        # a second of slack absorbs ffmpeg's frame granularity
        "-t", "%.3f" % ((want + MUSIC_RATE) / float(MUSIC_RATE)),
        "-ac", "1", "-ar", str(MUSIC_RATE),
        "-f", "s16le", "-acodec", "pcm_s16le", "pipe:1",
    ]
    try:
        proc = subprocess.run(cmd, check=True, stdout=subprocess.PIPE,
                              stderr=subprocess.PIPE)
    except (OSError, subprocess.CalledProcessError) as e:
        warn("ffmpeg failed for %s (%s)" % (src, e))
        return None

    samples = array.array("h")
    samples.frombytes(proc.stdout[:len(proc.stdout) & ~1])
    if sys.byteorder != "little":
        samples.byteswap()

    total = len(samples)
    if total < start + xfade + MUSIC_RATE:
        # Shorter than the requested offset plus a usable loop; loop from
        # the very beginning instead (the fade-in case).
        start = 0
    if total < xfade + MUSIC_RATE:
        # Very short source: keep it as-is with short fades at both ends.
        warn("%s is too short to crossfade; using a plain fade" % src)
        loop = min(total, loop)
        body = samples[:loop]
        fade = min(len(body) // 4, MUSIC_RATE // 4)
        for i in range(fade):
            body[i] = body[i] * i // fade
            body[len(body) - 1 - i] = body[len(body) - 1 - i] * i // fade
    else:
        if total < start + loop + xfade:
            loop = total - start - xfade
        body = samples[start + xfade:start + xfade + loop]
        for i in range(xfade):
            w = (i + 1) / float(xfade)
            j = loop - xfade + i
            body[j] = int(body[j] * (1.0 - w) + samples[start + i] * w)

    if target_db is not None:
        body = normalize_to_db(body, target_db)

    os.makedirs(os.path.dirname(dst), exist_ok=True)
    out = wave.open(dst, "wb")
    try:
        out.setnchannels(1)
        out.setsampwidth(2)
        out.setframerate(MUSIC_RATE)
        out.writeframes(body.tobytes())
    finally:
        out.close()

    nbytes = len(body) * 2
    if nbytes > MUSIC_MAX_BYTES:
        warn("music loop is %d bytes, over the %d byte target"
             % (nbytes, MUSIC_MAX_BYTES))
    return nbytes


def collect_tree_entries(newroot):
    """Return entries from a plain sounds/<key>/<n>.mp3 tree.

    The tree can be flat (soundpack/new/<key>/0.mp3) or nested
    (soundpack/new/you-hear/<slug>/0.mp3).  Any directory that directly
    holds audio files becomes a pack key named after that directory; a
    directory that only holds subdirectories is descended into (so the
    you-hear subfolders each become their own key).  The numbered files are
    the base sound (0) and its variations (1, 2, ...).  These files are
    normalized by convert(), so every entry gets volume 1.0 instead of the
    per-file volumes the manifest used.
    """
    out = []

    def walk(d):
        files = []
        subs = []
        for name in sorted(os.listdir(d)):
            p = os.path.join(d, name)
            if os.path.isdir(p):
                subs.append(p)
                continue
            stem, ext = os.path.splitext(name)
            if ext.lower() not in AUDIO_EXTS:
                continue
            order = int(stem) if stem.isdigit() else 10**6
            files.append((order, name.lower(), name))
        if files:
            files.sort()
            key = os.path.basename(d)
            rel = os.path.join("new", os.path.relpath(d, newroot)).replace("\\", "/")
            out.append((key, [("%s/%s" % (rel, name), 1.0)
                              for _, _, name in files]))
        for s in subs:
            walk(s)

    walk(newroot)
    return out


def collect_entries(soundpack):
    """Return [(key, [(src_relpath, volume), ...]), ...].

    A soundpack/new/<key>/<n>.mp3 tree, when present, takes precedence over
    the manifest.  That keeps the old manifest-based pack working while
    making it easy to drop in a freshly exported set of numbered files.
    """
    newroot = os.path.join(soundpack, "new")
    if os.path.isdir(newroot):
        return collect_tree_entries(newroot)

    manifest_path = os.path.join(soundpack, "manifest.json")
    if not os.path.isfile(manifest_path):
        return None
    with open(manifest_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    out = []
    for s in data.get("pack", {}).get("sounds", []):
        if not s.get("enabled", True):
            continue
        # entries that were never supplied have an empty path / null archive
        base = s.get("archivePath")
        if not s.get("path") or not base:
            continue
        files = [(base, float(s.get("volume", 1.0)))]
        for v in s.get("variations", []):
            if not v.get("enabled", True):
                continue
            ap = v.get("archivePath")
            if ap:
                files.append((ap, float(v.get("volume", 1.0))))
        out.append((s["key"], files))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--soundpack", default="soundpack",
                    help="directory holding manifest.json and sounds/")
    ap.add_argument("--romfs", default="romfs",
                    help="romfs root; sounds/ is written underneath")
    ap.add_argument("--out", default="build3ds/sndpack.h",
                    help="generated C header to write")
    ap.add_argument("--ffmpeg", default="ffmpeg",
                    help="ffmpeg executable to use")
    args = ap.parse_args()

    entries = collect_entries(args.soundpack)
    ffmpeg = shutil.which(args.ffmpeg) or (
        args.ffmpeg if os.path.isfile(args.ffmpeg) else None)

    # Music is independent of the effect manifest: soundpack/menu.mp3 and
    # soundpack/loop.mp3 (or soundpack/music/*) are enough.  Convert them
    # even when the effect list is empty, so a music-only pack still works.
    for stem, dstname, target_db in MUSIC_TRACKS:
        music_src = find_music(args.soundpack, stem)
        if not music_src:
            continue
        if ffmpeg:
            music_dst = os.path.join(args.romfs, "music", dstname + ".wav")
            n = convert_music(ffmpeg, music_src, music_dst, target_db)
            if n is not None:
                sys.stderr.write("build_sounds: music %s -> %s (%d bytes)\n"
                                 % (music_src, music_dst, n + 44))
        else:
            warn("ffmpeg (%s) not found; %s music skipped"
                 % (args.ffmpeg, stem))

    if entries is None:
        write_empty(args.out, "no manifest at %s/manifest.json"
                    % args.soundpack)
        return 0
    if not entries:
        write_empty(args.out, "the manifest lists no usable sounds")
        return 0
    if not ffmpeg:
        write_empty(args.out, "ffmpeg (%s) not found" % args.ffmpeg)
        return 0

    sounddir = os.path.join(args.romfs, "sounds")
    keys = []
    maxvars = 1
    converted = 0
    skipped = 0

    for key, files in entries:
        vols = []
        for n, (rel, vol) in enumerate(files):
            src = os.path.join(args.soundpack, *rel.split("/"))
            if not os.path.isfile(src):
                warn("missing %s for %s" % (src, key))
                if n == 0:
                    break  # no base sound: drop the whole key
                continue
            dst = os.path.join(sounddir, key, "%d.wav" % len(vols))
            if convert(ffmpeg, src, dst):
                vols.append(vol)
                converted += 1
            elif n == 0:
                break
        if vols:
            keys.append((key, vols))
            maxvars = max(maxvars, len(vols))
        else:
            skipped += 1

    _write_header(args.out, keys, maxvars)
    sys.stderr.write("build_sounds: %d sounds -> %s, %d keys, %d skipped\n"
                     % (converted, sounddir, len(keys), skipped))
    return 0


if __name__ == "__main__":
    sys.exit(main())
